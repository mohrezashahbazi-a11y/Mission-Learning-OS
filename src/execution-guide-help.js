  function decorate(){
    const panel=document.getElementById('executionGuidePanel');
    if(!panel)return;
    panel.querySelectorAll('.guideStep').forEach(step=>{
      const strong=step.querySelector('strong');
      const small=step.querySelector('small');
      if(!strong||!small||step.querySelector('.guideHelp'))return;
      const label=strong.textContent.replace(/^Step \d+ — /,'').trim();
      const text=HELP[label];
      if(!text)return;
      const help=document.createElement('div');
      help.className='guideHelp';
      help.style.cssText='margin-top:6px;padding:8px 10px;border-radius:8px;background:rgba(255,255,255,.035);line-height:1.65;color:var(--text);font-size:.9rem';
      help.innerHTML='<b>یعنی چی؟</b> '+text;
      small.insertAdjacentElement('afterend',help);
    });
  }
